import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const siteDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(siteDir, "../..");
const sourceDir = path.join(rootDir, "docs", "images");
const targetDir = path.join(rootDir, "site", "public", "assets", "real");
const files = ["logo.png", "animation.webp", "image-8.png", "image-10.png", "image-12.png", "image-13.png", "wechat-tip.png"];
fs.rmSync(targetDir, { recursive: true, force: true });
fs.mkdirSync(targetDir, { recursive: true });
for (const file of files) fs.copyFileSync(path.join(sourceDir, file), path.join(targetDir, file));
